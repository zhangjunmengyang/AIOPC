export function taskText(key: keyof typeof en) {
  return (currentLocale() === "zh" ? zh : en)[key];
}

export function taskError(error: unknown, fallback: keyof typeof en) {
  return error instanceof Error && error.message ? error.message : taskText(fallback);
}
